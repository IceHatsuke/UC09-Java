package Aula4;

public class NumtoPalavra {
    public static void main(String[] args) {
        int num;
        num = 3;
        if(num == 1)
        {
            System.out.println("UM");
        }
        else if(num == 2)
        {
            System.out.println("DOIS");
        }
        else
        {
            System.out.println("TRÊS");
        }
    }
}
