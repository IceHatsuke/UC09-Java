package Aula4;

public class PositivoNegativo {
    
    public static void main(String[] args) {
        
        int num;
        num = -1;

        if(num < 0)
        {
            System.out.println("É negativo");
        }
        else if(num > 0)
        {
            System.out.println("É positivo");
        }
        else
        {
            System.out.println("É zero");
        }
        
        
    }
}
